function applyLanguage(lang) {
  if (!translations[lang]) lang = "it";
  const dict = translations[lang];

  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.getAttribute("data-i18n");
    if (dict[key] !== undefined) el.textContent = dict[key];
  });

  document.querySelectorAll("[data-i18n-alt]").forEach((el) => {
    const key = el.getAttribute("data-i18n-alt");
    if (dict[key] !== undefined) el.setAttribute("alt", dict[key]);
  });

  document.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
    const key = el.getAttribute("data-i18n-placeholder");
    if (dict[key] !== undefined) el.setAttribute("placeholder", dict[key]);
  });

  const metaDesc = document.querySelector('meta[name="description"]');
  if (metaDesc && dict["meta.description"]) metaDesc.setAttribute("content", dict["meta.description"]);
  if (dict["meta.title"]) document.title = dict["meta.title"];

  document.documentElement.lang = lang;
  localStorage.setItem(GITTY_STELLA_LANG_KEY, lang);

  document.querySelectorAll("[data-lang-switch]").forEach((btn) => {
    btn.classList.toggle("active", btn.getAttribute("data-lang-switch") === lang);
  });
}

function detectInitialLanguage() {
  const saved = localStorage.getItem(GITTY_STELLA_LANG_KEY);
  if (saved && translations[saved]) return saved;

  const browserLang = (navigator.language || "it").slice(0, 2).toLowerCase();
  if (translations[browserLang]) return browserLang;

  return "it";
}

document.addEventListener("DOMContentLoaded", () => {
  applyLanguage(detectInitialLanguage());

  document.querySelectorAll("[data-lang-switch]").forEach((btn) => {
    btn.addEventListener("click", () => applyLanguage(btn.getAttribute("data-lang-switch")));
  });
});
